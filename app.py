import streamlit as st

# タイトル
st.title("☕️ カフェ混雑予想ツール")
st.write("今のシチュエーションを選んで、混雑確率をチェックしよう！")

# シチュエーションの選択肢
weather = st.radio("① 天候・気温", ["晴れ・曇り", "雨・悪天候"])
location = st.radio("② 立地条件", ["駅から徒歩5分以上", "駅直結・改札すぐ"])
time_slot = st.radio("③ 時間帯・曜日", ["平日（午前〜昼）", "土日祝（午後）"])
stay_type = st.radio("④ 周辺の店舗タイプ", ["テイクアウト・スタンド多め（高回転）", "作業・ノマド系カフェ（低回転）"])

# スコア計算ロジック
score = 0
if weather == "雨・悪天候":
    score += 25
if location == "駅直結・改札すぐ":
    score += 35
if time_slot == "土日祝（午後）":
    score += 25
if stay_type == "作業・ノマド系カフェ（低回転）":
    score += 15

# 判定ボタンと結果表示
if st.button("混雑度を予想する"):
    st.subheader(f"予想混雑度: {score}%")
    
    if score >= 70:
        st.error("🚨 【激混み予想】満席の可能性が高いです！")
        st.write("👉 **おすすめの立ち回り:** 駅から徒歩7分以上離れたビル上階のカフェや、テイクアウト専門スタンドを狙うのがベストです。")
    elif score >= 40:
        st.warning("⚠️ 【やや混雑】タイミングによって並ぶ可能性があります。")
        st.write("👉 **おすすめの立ち回り:** 一度覗いてみてダメなら、少し離れたエリアへ移動するのが無難です。")
    else:
        st.success("✨ 【空いている可能性高】スムーズに入れる期待大！")
        st.write("👉 **おすすめの立ち回り:** お目当てのカフェにそのまま向かってOKです。")